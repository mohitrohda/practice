#You bought 9 packets of potato chips from a store. Each packet costs 1.49 dollar and you gave shopkeeper 20 dollar.
#Find out using python, how many dollars is the shopkeeper going to give you back?

potato_chips = 9
price_of_one_potato_chips= 1.49

total_price_of_potato_chips = potato_chips * price_of_one_potato_chips

return_money_by_shopkeeper = 20 - total_price_of_potato_chips

print("Shopkeeper Return money =",return_money_by_shopkeeper)
